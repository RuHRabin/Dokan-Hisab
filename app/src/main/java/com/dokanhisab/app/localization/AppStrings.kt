    fun providerLabel(provider: AiProvider): String = when (provider) {
        AiProvider.GEMINI -> providerGeminiLabel
        AiProvider.OPENROUTER -> providerOpenRouterLabel
    }

    fun currencyLabel(@Suppress("UNUSED_PARAMETER") option: CurrencyOption): String = currencyFixedValue

    private val isBangla: Boolean
        get() = navDashboard == "হিসাব"
}

