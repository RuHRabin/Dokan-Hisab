    fun periodLabel(period: TimePeriod): String = when (period) {
        TimePeriod.TODAY -> periodToday
        TimePeriod.THIS_MONTH -> periodMonth
        TimePeriod.THIS_YEAR -> periodYear
        TimePeriod.ALL_TIME -> periodAll
    }

    fun typeFilterLabel(filter: TypeFilter): String = when (filter) {
        TypeFilter.ALL -> filterAll
        TypeFilter.INCOME -> filterIncome
        TypeFilter.EXPENSE -> filterExpense
    }

    fun transactionTypeLabel(type: TransactionType): String = when (type) {
        TransactionType.INCOME -> filterIncome
        TransactionType.EXPENSE -> filterExpense
    }

    fun paymentMethodLabel(method: PaymentMethod): String = when (method) {
        PaymentMethod.CASH -> if (isBangla) "নগদ" else "Cash"
        PaymentMethod.MOBILE_BANKING -> if (isBangla) "বিকাশ/নগদ" else "Mobile Pay"
        PaymentMethod.BANK -> if (isBangla) "ব্যাংক" else "Bank"
        PaymentMethod.DUE_CREDIT -> if (isBangla) "বাকি" else "Due / Baki"
    }

    fun themeModeLabel(mode: ThemeMode): String = when (mode) {
        ThemeMode.SYSTEM -> themeSystem
        ThemeMode.LIGHT -> themeLight
        ThemeMode.DARK -> themeDark
    }

    fun paletteLabel(palette: AppPalette): String = if (isBangla) {
        when (palette) {
            AppPalette.EMERALD -> "এমারেল্ড সবুজ"
            AppPalette.ROYAL_BLUE -> "রয়েল নীল"
            AppPalette.CLASSIC_AMBER -> "সোনালি অ্যাম্বার"
            AppPalette.SLATE_GRAY -> "স্লেট ধূসর"
            AppPalette.CRIMSON_ROSE -> "ক্রিমসন লাল"
        }
    } else {
        when (palette) {
            AppPalette.EMERALD -> "Emerald Green"
            AppPalette.ROYAL_BLUE -> "Royal Blue"
            AppPalette.CLASSIC_AMBER -> "Classic Amber"
            AppPalette.SLATE_GRAY -> "Slate Gray"
            AppPalette.CRIMSON_ROSE -> "Crimson Rose"
        }
    }

    fun modelLabel(model: GeminiChatModel): String = when (model) {
        GeminiChatModel.HYDROGEN -> modelHydrogenLabel
        GeminiChatModel.CARBON -> modelCarbonLabel
        GeminiChatModel.ARGON -> modelArgonLabel
        GeminiChatModel.FLASH_LITE -> modelFlashLiteLabel
